"""Export only public location matching fields, never course records/config."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def quote(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')


def export(source):
    raw = source.read_bytes()
    data = json.loads(raw.decode('utf-8-sig'))
    assert data['coordinateSystem'] == 'GCJ-02'
    groups = {g['id']: g for g in data['placeGroups']}
    buildings = [b for b in data['buildings'] if not b.get('excludedFromPresets')]
    assert len({b['id'] for b in buildings}) == len(buildings)
    lines = ['// GENERATED by scripts/export_teaching_catalog.py. Do not edit.',
             f'// Source SHA256: {hashlib.sha256(raw).hexdigest()}',
             "part of 'teaching_catalog.dart';", '',
             f'const teachingCatalogSha256 = {quote(hashlib.sha256(raw).hexdigest())};',
             'const teachingBuildings = <TeachingBuilding>[']

    def centroid(vertices):
        if len(vertices) < 3:
            return None
        ox, oy = vertices[0]['longitude'], vertices[0]['latitude']
        area = x = y = 0
        for a, b in zip(vertices, vertices[1:] + vertices[:1]):
            ax, ay, bx, by = a['longitude'] - ox, a['latitude'] - oy, b['longitude'] - ox, b['latitude'] - oy
            cross = ax * by - bx * ay
            area += cross
            x += (ax + bx) * cross
            y += (ay + by) * cross
        return dict(longitude=ox + x / (3 * area), latitude=oy + y / (3 * area)) if abs(area) > 1e-12 else None

    def point(key, name, campus, value, kind):
        if not value:
            return 'null'
        lat, lon = value['latitude'], value['longitude']
        assert math.isfinite(lat) and -90 <= lat <= 90
        assert math.isfinite(lon) and -180 <= lon <= 180
        legacy = {'xa-xuewu': 'xuewu', 'xa-kunluan': 'kunluan', 'xa-wenxuan': 'wenxuan'}
        prefix, _, code = key.partition(':')
        stable = f'{legacy[prefix]}-{code.lower()}' if prefix in legacy and code in 'ABC' and code else key
        if key == 'xa-west2':
            stable = 'west-2'
        if key == 'xa-west4':
            stable = 'west-4'
        source_kind = 'polygon_centroid' if value.get('source') == 'polygon_centroid' else kind
        return f'TeachingPoint({quote("xmu:teaching:" + stable)}, {quote(name)}, {quote(campus)}, {float(lat)!r}, {float(lon)!r}, {quote(source_kind)})'

    def array(values):
        return '[' + ', '.join(quote(v) for v in dict.fromkeys(values) if v) + ']'

    for b in buildings:
        campus, name = b['campus'], b['name']
        group = groups.get(b.get('groupId'), {})
        fallback = (centroid(group.get('area', {}).get('vertices', [])) or group.get('point')) if b.get('fallbackToGroup') else None
        bp = b.get('point') or fallback
        base = name.split('（')[0].split('(')[0]
        lines.append(f'TeachingBuilding({quote(b["id"])}, {quote(name)}, {quote(campus)}, {array(b.get("aliases", []))}, [')
        valid_targets = {b['id'], *[r['id'] for r in b['regions']]}
        for a in b.get('matchingAliases', []):
            target = a.get('target_id', b['id'])
            if target not in valid_targets:
                raise ValueError(f'Unknown alias target: {b["id"]} {target}')
            scope = a.get('scope', {})
            values = [a['alias'], target, scope.get('campus', a.get('campus', campus)), scope.get('department', ''), scope.get('groupId', ''), scope.get('event', '')]
            lines.append('TeachingAlias(' + ', '.join(quote(v) for v in values) + ', ' + str(bool(scope.get('department') or a.get('room'))).lower() + '),')
        lines.append('], [')
        for r in b['regions']:
            code = r['code']
            display = r.get('displayName') or r['name']
            if b['id'] in ['xa-xuewu', 'xa-kunluan', 'xa-wenxuan']:
                display = f'{base} {code}区'
            elif not any(word in display for word in ['楼', '座', '栋']) and not display.startswith(base):
                display = base + (display if display.endswith('区') else display + '区')
            linked = next((other.get('point') for other in b['regions'] if other['id'] == r.get('pointFromRegion')), None)
            rp = r.get('point') or linked or bp
            kind = 'region' if r.get('point') else 'linked_region' if linked else 'building' if b.get('point') else 'group'
            names = [display, *r.get('aliases', [])]
            lines.append(f'TeachingRegion({quote(r["id"])}, {quote(code)}, {array(names)}, {point(r["id"], display, campus, rp, kind)}),')
        lines.append(f'], {point(b["id"], name, campus, bp, "building" if b.get("point") else "group")}, groupId: {quote(b.get("groupId", ""))}),')
    lines.extend(['];', '', 'const teachingGroups = <TeachingGroup>['])
    for g in groups.values():
        gp = centroid(g.get('area', {}).get('vertices', [])) or g.get('point')
        vertices = '[' + ', '.join(f'(latitude: {float(v["latitude"])!r}, longitude: {float(v["longitude"])!r})' for v in g.get('area', {}).get('vertices', [])) + ']'
        lines.append(f'TeachingGroup({quote(g["id"])}, {quote(g["name"])}, {quote(g["campus"])}, {array(g.get("aliases", []))}, {point("group:" + g["id"], g["name"], g["campus"], gp, "group")}, kind: {quote(g.get("kind", ""))}, vertices: {vertices}),')
    lines.extend(['];', ''])
    output = ROOT / 'lib/features/location/teaching_catalog.g.dart'
    output.write_text('\n'.join(lines), encoding='utf-8')
    subprocess.run(['dart.bat', 'format', str(output)], check=True)
    print(f'{len(buildings)} buildings exported; source {hashlib.sha256(raw).hexdigest()}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'tools/location_picker/data/locations.json')
    export(parser.parse_args().source)
